"""Generate workflow configs from a scene directory.

Inspects a scene directory -- a 3DGS ``.ply``, a COLMAP model and the photos,
in any of the layouts ``config.detect_scene`` recognises -- and writes the
three configs the workflow needs:

    configs/scenes/generated/<name>/
      workflow.yaml   the file you pass to run.py
      find.yaml       repair_view_finder scene config
      repair.yaml     repair_pipeline scene config

The sub-configs stay separate on purpose: each is a valid config for its own
project, so the stage can still be run standalone while debugging.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from .config import ROOT, detect_scene


def _write(path: Path, payload: dict, header: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = yaml.safe_dump(payload, sort_keys=False, allow_unicode=True)
    path.write_text(f"# {header}\n{text}", encoding="utf-8")


def _units(value) -> float | str:
    """``geometry.units_per_metre`` for the finder: a positive number or ``auto``."""
    if str(value).strip().lower() == "auto":
        return "auto"
    number = float(value)
    if number <= 0:
        raise SystemExit(f"--units-per-metre must be positive or 'auto', got {value!r}")
    return number


# The finder's path presets for captures that walk around a subject.
# make-config copies the preset's `trajectories:` block rather than repeating
# the numbers, so each preset has one home. "default" keeps method.yaml's
# indoor, robot-height settings.
_SCENES = ROOT / "subprojects" / "repair_view_finder" / "configs" / "scenes"
PATH_PRESETS = {
    "default": None,
    "object-centric": _SCENES / "example_object_centric.yaml",          # outdoor, open ground
    "object-centric-indoor": _SCENES / "example_object_centric_indoor.yaml",  # tables, small rooms
}
OBJECT_CENTRIC = PATH_PRESETS["object-centric"]


def generate(scene_root: Path, out_dir: Path, variant: str = "1.3b",
             mask_invalid: str | None = None, units_per_metre="auto",
             paths: str = "default") -> Path:
    """``units_per_metre``: scene units per metre, or ``auto`` (estimated from the
    camera height above the floor). A COLMAP model has an arbitrary scale, so
    ``auto`` is the default; pass 1 for a metric capture.

    ``paths``: which finder path settings to write -- ``default`` (low indoor,
    robot height), ``object-centric`` (walking around a subject outdoors) or
    ``object-centric-indoor`` (around a table or in a small room); see
    PATH_PRESETS."""
    if paths not in PATH_PRESETS:
        raise SystemExit(f"unknown path preset {paths!r}; choose from {sorted(PATH_PRESETS)}")
    scene_root = Path(scene_root).resolve()
    info = detect_scene(scene_root)
    # `find` only needs the 3DGS and the SfM; the photos are first read by the
    # reference-view step. Requiring them here would block stage 1 on a dataset
    # whose images are still being copied.
    missing = [k for k in ("ply", "sparse") if info[k] is None]
    if missing:
        raise SystemExit(
            f"{scene_root}: cannot find {missing}. "
            f"Layout seen: {sorted(p.name for p in scene_root.iterdir())}. "
            f"Name the paths in a scene config instead (see configs/scenes/example.yaml)."
        )
    name = info["name"]
    if mask_invalid is None:
        mask_invalid = "white" if info["has_masks"] else "none"

    target = Path(out_dir) / name
    find_cfg = target / "find.yaml"
    repair_cfg = target / "repair.yaml"
    workflow_cfg = target / "workflow.yaml"

    _write(find_cfg, {
        "scene": {
            "root": str(scene_root),
            "ply": info["ply"].as_posix(),
            "sparse": info["sparse"].as_posix(),
            "frame_label": "unknown",
        },
        "geometry": {"units_per_metre": _units(units_per_metre)},
        **({"trajectories": yaml.safe_load(PATH_PRESETS[paths].read_text(encoding="utf-8"))["trajectories"]}
           if PATH_PRESETS[paths] else {}),
    }, f"generated by nvs_repair make-config for {name} (stage 1)")

    _write(repair_cfg, {
        "scene": {
            "root": str(scene_root),
            "ply": info["ply"].as_posix(),
            "sparse": info["sparse"].as_posix(),
            "images": info["images"].as_posix() if info["images"] else "images",
            "mask_invalid": mask_invalid,
            "name": name,
        },
    }, f"generated by nvs_repair make-config for {name} (stage 2)")

    _write(workflow_cfg, {
        "scene": {"root": str(scene_root)},
        "out": f"outputs/{name}",
        "find": {"config": str(find_cfg), "set": [], "limit_views": None},
        "model": {"variant": variant},
        "repair": {"config": str(repair_cfg), "set": [], "limit": None},
    }, f"generated by nvs_repair make-config for {name}")
    return workflow_cfg


def discover(batch_root: Path) -> list[Path]:
    """Scene directories under a batch root (those that look like a scene)."""
    batch_root = Path(batch_root)
    out = []
    for child in sorted(p for p in batch_root.iterdir() if p.is_dir()):
        info = detect_scene(child)
        if info["ply"] and info["sparse"]:
            out.append(child)
    return out
