"""Workflow config: defaults, per-scene overrides, machine-local env paths.

Three layers, same convention as the two subprojects so they read alike:

    configs/workflow.yaml      repository defaults, no absolute paths
    configs/scenes/<x>.yaml    one scene: output dir, sub-config paths, overrides
    configs/envs.local.yaml    generated by bootstrap.sh: interpreters + checkout

Anything can be overridden with ``--set a.b=value``.
"""

from __future__ import annotations

import os
from pathlib import Path

from omegaconf import DictConfig, OmegaConf

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_WORKFLOW = ROOT / "configs" / "workflow.yaml"
LOCAL_ENVS = ROOT / "configs" / "envs.local.yaml"


def _abs(value: str) -> str:
    """Resolve a config path against the repository root unless already absolute."""
    p = Path(value).expanduser()
    return str(p) if p.is_absolute() else os.path.normpath(ROOT / p)


def load(path: str, overrides: list[str] | None = None) -> DictConfig:
    scene = OmegaConf.load(path)
    layers = [OmegaConf.load(DEFAULT_WORKFLOW)]
    if LOCAL_ENVS.is_file():
        layers.append(OmegaConf.load(LOCAL_ENVS))
    layers.append(scene)
    cfg = OmegaConf.merge(*layers)
    if overrides:
        cfg = OmegaConf.merge(cfg, OmegaConf.from_dotlist(overrides))
    OmegaConf.resolve(cfg)

    # Outputs: one root, one subdirectory per stage. Keeping the default inside
    # the repo means a fresh clone writes somewhere findable without edits.
    out = cfg.out or f"outputs/{Path(path).stem}"
    cfg.out = _abs(str(out))

    # Weights live in <repo>/checkpoints, so a config never carries a machine
    # path; they can be symlinks to an existing download. Two keys on
    # purpose: `checkpoints_dir` is the directory, `checkpoints` is the map of
    # what lives inside it (relative paths).
    cfg.checkpoints_dir = _abs(str(cfg.checkpoints_dir))
    # Relative to the repo too, so a relocatable install (the Windows bundle
    # ships envs.local.yaml with "../ArtiFixer") works wherever it is unpacked.
    if cfg.get("paths") and cfg.paths.get("artifixer_repo"):
        cfg.paths.artifixer_repo = _abs(str(cfg.paths.artifixer_repo))
    if not cfg.checkpoints.get("text_encoder"):
        cfg.checkpoints.text_encoder = cfg.checkpoints.artifixer[str(cfg.model.variant)].model_id

    if not cfg.scene or not cfg.scene.get("root"):
        raise ValueError("scene.root is required (used for the default output name)")
    if not cfg.find or not cfg.find.get("config"):
        raise ValueError("find.config must point at a repair_view_finder scene config")
    if not cfg.repair or not cfg.repair.get("config"):
        raise ValueError("repair.config must point at a repair_pipeline scene config")
    cfg.find.config = _abs(str(cfg.find.config))
    cfg.repair.config = _abs(str(cfg.repair.config))
    for name in ("find", "repair"):
        cfg[name].set = list(cfg[name].get("set") or [])

    return cfg


def variant(cfg: DictConfig) -> str:
    """Which checkpoint pair the repair stage should use.

    One source of truth: the top-level ``model.variant``, so it can be switched
    per run with ``--set model.variant=14b``.
    """
    return str(cfg.model.variant)


def dump(cfg: DictConfig) -> dict:
    return OmegaConf.to_container(cfg, resolve=True)

# Common layouts `make-config` recognises; anything else can be named
# explicitly in a scene config (see configs/scenes/example.yaml).
_PLY_CANDIDATES = ("point_cloud.ply", "splat.ply", "output/point_cloud/point_cloud.ply")
_PLY_ITERATION_DIRS = ("point_cloud", "output/point_cloud")
_SPARSE_CANDIDATES = ("sparse/0", "sparse")


def _latest_iteration_ply(root: Path) -> Path | None:
    """``point_cloud/iteration_<N>/point_cloud.ply`` with the largest N (3DGS / gsplat output)."""
    best = None
    for rel in _PLY_ITERATION_DIRS:
        for d in (root / rel).glob("iteration_*"):
            ply = d / "point_cloud.ply"
            step = d.name.split("_", 1)[-1]
            if ply.is_file() and step.isdigit() and (best is None or int(step) > best[0]):
                best = (int(step), ply)
    return best[1] if best else None


def detect_scene(root: Path) -> dict:
    """Work out where the 3DGS model, the COLMAP model and the photos live.

    * ``point_cloud.ply`` / ``splat.ply`` at the scene root, or the latest
      ``point_cloud/iteration_<N>/point_cloud.ply`` (3DGS training output)
    * COLMAP model in ``sparse/0/`` or ``sparse/`` (``cameras.bin`` or ``.txt``)
    * photos in ``images/``
    """
    root = Path(root)
    ply = (next((root / rel for rel in _PLY_CANDIDATES if (root / rel).is_file()), None)
           or _latest_iteration_ply(root))
    sparse = next((root / rel for rel in _SPARSE_CANDIDATES
                   if (root / rel / "cameras.bin").is_file()
                   or (root / rel / "cameras.txt").is_file()), None)
    images = root / "images" if (root / "images").is_dir() else None
    return {
        "ply": ply.relative_to(root) if ply else None,
        "sparse": sparse.relative_to(root) if sparse else None,
        "images": images.relative_to(root) if images else None,
        "has_masks": bool(images and any(images.glob("mask_*"))),
        "name": root.name,
    }
